'use strict';
const assert=require('node:assert/strict'),M=require('./dist/model.js');
const find=title=>M.slides.findIndex(s=>s.title===title);
const challenge=find('Un reto antes de las ecuaciones');
const construction=find('Dos familias monoparamétricas');
const applied=find('¿Qué hicieron los investigadores con esta idea?');
const conclusion=find('Del ángulo al problema real');
assert.equal(challenge,3);
assert.ok(challenge<construction&&construction<applied&&applied<conclusion);
assert.equal(M.slides[challenge].graph,'engineering-question');
assert.equal(M.slides[challenge].section,'Introducción');
assert.ok(M.slides[challenge].body.some(b=>(b.value||'').includes('¿Trazarías')));
assert.ok(M.slides[challenge].notes.includes('NO RESULTADO EXPERIMENTAL'));
const intro=M.slides[applied].body.map(b=>b.value||'').join(' ');
assert.ok(intro.includes('Galanin y Feodorova (2017)'));
assert.ok(intro.includes('ecuaciones diferenciales'));
const close=M.slides[conclusion].body.map(b=>b.value||b.tex||'').join(' ');
assert.ok(close.includes('2017 y 2019'));
assert.ok(close.includes('ingeniería'));
assert.ok(M.slides[conclusion].duration>=30);
assert.equal(M.slides.reduce((n,s)=>n+s.duration,0),1255);
assert.equal(M.slides.filter(s=>!s.optional).length,35);
assert.equal(M.slides.filter(s=>s.optional).length,5);
assert.deepEqual(M.sections.map(s=>s.slide),[4,10,17,26,37]);
console.log('Puente didáctico: reto inicial, matemática, investigación, conclusión y 20:55 correctos.');
